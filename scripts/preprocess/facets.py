"""facets.py — the DuckDB-WASM inputs: parcels_attr.parquet + facets.json.

Two ``--app-assets`` outputs per state, generated by DuckDB straight
from the parcel parquet (PRD #135 stage 4 — the slim parquet is sorted
and written out-of-core; the whole-state attribute table never
materialises in Python):

- **parcels_attr.parquet** — the filterable / searchable / displayable
  columns only. The three WKB geometry columns, the ``extras`` blob and
  every ``_``-prefixed internal column are dropped; ``geom_bbox`` (a
  plain string — lets the app fly-to a parcel without geometry) and the
  JSON-string nested columns (``interestingness_components``,
  ``infrastructure_summary``, ``distress_overlays``) are kept. Written
  with many small row groups, sorted by ``interestingness_score``
  descending (ties broken by source file order, so the output is
  deterministic). DuckDB-WASM range-queries this file.
- **facets.json** — distinct categorical values + counts and numeric
  min/max, so the filter controls render instantly without a DuckDB
  round-trip. Computed over the written parcels_attr.parquet — exactly
  the file the app queries.
"""

from __future__ import annotations

import json
import logging
import os
import tempfile
from pathlib import Path

import duckdb
import pyarrow as pa
import pyarrow.parquet as pq

from . import COMPOSITE_ROOT, duck

log = logging.getLogger("preprocess.facets")

# Columns excluded from parcels_attr.parquet: the WKB geometry columns
# and the extras blob (every _-prefixed internal column is also dropped).
_DROP_EXACT: frozenset[str] = frozenset({"geometry", "geom_centroid", "geom_simplified", "extras"})

CATEGORICAL_FACETS: tuple[str, ...] = (
    "owner_kind",
    "distress_tier",
    "land_use_desc",
    "county_fips",
)
NUMERIC_FACETS: tuple[str, ...] = (
    "assessed_value",
    "acreage",
    "interestingness_score",
    "owner_cluster_size",
)
SORT_COLUMN = "interestingness_score"
ROW_GROUP_SIZE = 16384
# Cap categorical facet lists so facets.json stays small (< 100 KB/state).
MAX_CATEGORICAL_VALUES = 200
FACETS_SCHEMA_VERSION = 1


def attr_columns(all_columns: list[str]) -> list[str]:
    """The columns kept in parcels_attr.parquet (drops geometry + internals)."""
    return [c for c in all_columns if c not in _DROP_EXACT and not c.startswith("_")]


def _compute_facets_sql(con: duckdb.DuckDBPyConnection, attr_path: Path) -> dict:
    """Distinct categorical values + counts, and numeric min/max — one SQL
    aggregation per facet over the written parcels_attr.parquet.

    Mirrors the retired pyarrow value_counts path (equivalence pinned by
    tests/test_duckdb_equivalence.py): null / empty-string categorical
    values are dropped, lists are capped at MAX_CATEGORICAL_VALUES by
    count. Ties at the same count are ordered by value (the legacy order
    among equal counts was encounter-order — non-contractual; this makes
    the file deterministic).
    """
    src = f"read_parquet({duck.sql_str(str(attr_path))})"
    schema = pq.read_schema(attr_path)
    types = {name: schema.field(name).type for name in schema.names}

    total = int(con.execute(f"SELECT count(*) FROM {src}").fetchone()[0])

    categorical: dict[str, list[dict]] = {}
    for col in CATEGORICAL_FACETS:
        if col not in types:
            continue
        # The empty-string drop only applies to string columns (matching
        # `value == ""` against a non-string, which never matched).
        blank = f" AND \"{col}\" != ''" if pa.types.is_string(types[col]) else ""
        rows = con.execute(
            f"""
            SELECT "{col}" AS value, CAST(count(*) AS BIGINT) AS count
            FROM {src}
            WHERE "{col}" IS NOT NULL{blank}
            GROUP BY 1
            ORDER BY count DESC, value ASC
            LIMIT {MAX_CATEGORICAL_VALUES}
            """
        ).fetchall()
        categorical[col] = [{"value": value, "count": int(count)} for value, count in rows]

    numeric: dict[str, dict] = {}
    for col in NUMERIC_FACETS:
        if col not in types:
            continue
        mn, mx = con.execute(f'SELECT min("{col}"), max("{col}") FROM {src}').fetchone()
        numeric[col] = {"min": mn, "max": mx}

    return {
        "schema_version": FACETS_SCHEMA_VERSION,
        "total": total,
        "categorical": categorical,
        "numeric": numeric,
    }


def _write_json_atomic(payload: dict, path: Path) -> None:
    tmp_fd, tmp_name = tempfile.mkstemp(dir=path.parent, prefix=f".{path.stem}.", suffix=".tmp")
    try:
        with os.fdopen(tmp_fd, "w") as f:
            json.dump(payload, f, indent=2, sort_keys=True)
        Path(tmp_name).replace(path)
    except Exception:
        Path(tmp_name).unlink(missing_ok=True)
        raise


def build_facets(state_fips: str, *, composite_root: Path | None = None) -> dict:
    """Write parcels_attr.parquet + facets.json for one state.

    One DuckDB ``COPY (SELECT … ORDER BY …)`` projects the attribute
    columns and sorts out-of-core — the per-shard read-and-concat that
    materialised the whole state in Python is gone (PRD #135 stage 4).
    The column list comes from the first source file's schema (a column
    missing from a later shard reads as NULL, like the old promoting
    concat). Sort ties break on source file order so the output is
    deterministic; with no sort column the source order is preserved.

    Raises FileNotFoundError when the state has neither parcels.parquet
    nor a parcels/ shard directory.
    """
    from .app_assets import resolve_parcel_paths

    root = composite_root if composite_root is not None else COMPOSITE_ROOT
    state_dir = root / state_fips
    paths, is_sharded = resolve_parcel_paths(state_dir)

    schema_names = pq.ParquetFile(paths[0]).schema_arrow.names
    keep = attr_columns(schema_names)
    # A column that is null-typed in every source file (all values null —
    # e.g. situs_state in MT) has no real type for DuckDB to carry; cast it
    # to VARCHAR so the written file round-trips to the same pandas object
    # dtype the legacy engine produced (arrow `null` type would otherwise
    # come back as int32-nulls → float64).
    all_null: set[str] = set(keep)
    for path in paths:
        schema = pq.read_schema(path)
        fields = {schema.field(i).name: schema.field(i).type for i in range(len(schema))}
        all_null = {c for c in all_null if pa.types.is_null(fields.get(c, pa.null()))}
        if not all_null:
            break
    cols_sql = ", ".join(
        f'CAST(p."{c}" AS VARCHAR) AS "{c}"' if c in all_null else f'p."{c}"' for c in keep
    )
    paths_sql = ", ".join(duck.sql_str(str(x)) for x in paths)
    order_sql = (
        f'p."{SORT_COLUMN}" DESC NULLS LAST, p.filename ASC, p.file_row_number ASC'
        if SORT_COLUMN in keep
        else "p.filename ASC, p.file_row_number ASC"
    )

    attr_path = state_dir / "parcels_attr.parquet"
    tmp_fd, tmp_name = tempfile.mkstemp(
        dir=attr_path.parent, prefix=f".{attr_path.stem}.", suffix=".tmp"
    )
    os.close(tmp_fd)
    tmp = Path(tmp_name)
    rows = 0
    try:
        with duck.session() as con:
            tmp.unlink()  # COPY creates the file itself
            con.execute(
                f"""
                COPY (
                  SELECT {cols_sql}
                  FROM read_parquet([{paths_sql}],
                                    union_by_name=true, filename=true, file_row_number=true) p
                  ORDER BY {order_sql}
                ) TO {duck.sql_str(str(tmp))}
                  (FORMAT PARQUET, COMPRESSION ZSTD, ROW_GROUP_SIZE {ROW_GROUP_SIZE})
                """
            )
            tmp.replace(attr_path)
            facets = _compute_facets_sql(con, attr_path)
            rows = facets["total"]
    except Exception:
        tmp.unlink(missing_ok=True)
        raise

    facets["state_fips"] = state_fips
    facets_path = state_dir / "facets.json"
    _write_json_atomic(facets, facets_path)

    log.info(
        "wrote %s (%d cols, %s) + %s",
        attr_path,
        len(keep),
        "sharded" if is_sharded else "single-file",
        facets_path,
    )
    return {"attr_path": str(attr_path), "facets_path": str(facets_path), "rows": rows}


def _states_with_parcels(composite_root: Path) -> list[str]:
    """States that have either a parcels.parquet or a parcels/ shard dir."""
    from .app_assets import iter_composed_states, state_has_parcels

    return iter_composed_states(composite_root, predicate=state_has_parcels)


def run_facets(state_fips: str | None = None, *, composite_root: Path | None = None) -> dict:
    """Build facets + the slim parquet for one state or every composed state."""
    root = composite_root if composite_root is not None else COMPOSITE_ROOT
    states = [state_fips] if state_fips else _states_with_parcels(root)
    ok: list[str] = []
    failed: list[str] = []
    for fips in states:
        try:
            build_facets(fips, composite_root=root)
            ok.append(fips)
        except Exception as exc:  # noqa: BLE001 — one state's failure must not abort the rest
            log.error("facets failed for state %s: %s", fips, exc)
            failed.append(fips)
    return {"ok": ok, "failed": failed}
